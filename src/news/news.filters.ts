/**
 * Шумовые заголовки: общие сводки и дайджесты. Такие посты брокер и каналы
 * помечают всеми тикерами сразу, но к конкретной бумаге они не относятся.
 */
export const DIGEST_TITLE =
  /утренн|вечерн|дайджест|итоги (дня|недели|месяца|торгов|рынка|квартала|года)|главное за|обзор рынка|что случилось|расписание|календарь|подборк|топ-\d|инвест-дайджест|weekly|daily digest|неделя на рынке|обзор недели|корпоративные события|идеи недели|что купить/i;

/** Заголовок — общая сводка, а не новость по бумаге. */
export const isDigestTitle = (title: string): boolean => DIGEST_TITLE.test(title);

/**
 * Публикации вне инвестиционной повестки: спорт, развлечения, происшествия,
 * неэкономическая политика. Нужны общей новостной сводке, где нет портфеля и
 * фильтра по бумагам.
 */
export const OFF_TOPIC_TITLE =
  /спорт|матч|футбол|хокке|теннис|олимпи|чемпионат|тренер|голы|кхл|нхл|фильм|сериал|премьер|режисс|актёр|актер|концерт|шоу|звезда|фоторепортаж|гороскоп|рецепт|погода|дтп|пожар|убийств|задержан|приговор|развод|знаменитост|телеведущ|инстаграм|тикток|акци[яию]х?\s+(?:по|всеобщ|протест)|забастовк|гумпомощ|возвращени[еяю] детей|церков|патриарх|фестивал|выставк|конкурс красоты|митинг|протест|подал в отставку|на проект развития|реконструкц|благоустройств|капремонт|поликлиник|водоснабж|детск(?:ий|ого) сад|мировой суд/i;

/** Заголовок или аннотация не относятся к инвестиционной повестке. */
export const isOffTopicTitle = (title: string, summary?: string): boolean =>
  OFF_TOPIC_TITLE.test(title) || OFF_TOPIC_TITLE.test(summary ?? '');

/**
 * Маркеры инвестиционной повестки: без хотя бы одного из них публикацию из
 * общей ленты в сводку не берём — иначе туда попадают некрологи и культура.
 */
export const INVESTMENT_MARKER =
  /(?<![а-яa-z])(?:рынк|акци|облигац|дивиденд|ставк|центробанк|цб|инфляц|рубл|доллар|нефт|золот|металл|индекс|мосбирж|бирж|эмитент|отчётн|отчетн|выручк|прибыл[ьи]|убыт|ipo|spo|etf|фьючерс|котиров|капитализац|инвест|брокер|регулятор|санкц|тариф|налог|бюджет|ввп|экспорт|импорт|экономик|ипотек|кредит|депозит|банк|фонд|акционер|аналитик)/i;

/** Публикация относится к инвестиционной повестке. */
export const hasInvestmentMarker = (title: string, summary?: string): boolean =>
  INVESTMENT_MARKER.test(title) || INVESTMENT_MARKER.test(summary ?? '');
