/**
 * Вопрос про состав портфеля: данные нужны всегда, без решения модели. Правило
 * живёт в маршрутизации, а не в узле ответа — узел читает `dataNeed`.
 */
export const PORTFOLIO_DATA_PATTERN =
  /портфел|позици|позиций|по счёт|по счет|счетам|счетах|счётам|счетам|что у меня|сколько у меня|мои бумаг|мой счёт|мой счет/i;

/** Нужно ли для вопроса читать состав портфеля. */
export const needsPortfolioData = (question: string): boolean =>
  PORTFOLIO_DATA_PATTERN.test(question);
