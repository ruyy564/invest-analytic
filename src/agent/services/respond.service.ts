import type { NodeResult } from '../results/index.js';

/**
 * Отказ модели вместо раздела: провайдеры (GigaChat) иногда отвечают
 * «я не обладаю мнением» или «разговоры на эту тему ограничены». Такой текст
 * в отчёт не идёт — вместо него подставляются факты брифинга.
 */
export const REFUSAL =
  /не облада(?:ет|ют) собственным мнением|как и любая языковая модель|языковые модели|разговоры на (?:некоторые|чувствительные|эту) темы|чувствительн[а-яё]* тем|временно ограничен|неправильн[а-яё]* толковани|некорректные ответы|не могу (?:дать|предоставить|комментировать|обсуждать)|не являюсь инвестиционным советником/i;

/** Ответ модели — отказ, а не содержательный текст. */
export const isRefusal = (text: string): boolean => REFUSAL.test(text);

/**
 * Отказ показать данные, хотя они уже получены: «не могу предоставить»,
 * «обратитесь к брокеру», «уточните запрос». Для портфельных вопросов вместо
 * такого ответа подставляется вызов инструмента.
 */
export const DATA_REFUSAL =
  /не могу (?:предоставить|показать|получить)|техническ|обратитесь к (?:вашему )?брокеру|в приложени[еи] брокера|(?:данные|информаци[а-яё]*) (?:сейчас )?недоступн|уточните запрос|нет доступа к данным/i;

/** Бесполезный ответ: пустой, отказ модели или отказ показать данные. */
export const isDataRefusal = (text: string): boolean => REFUSAL.test(text) || DATA_REFUSAL.test(text);

/** Факты брифинга как текст раздела: строки «поле: значение» через «•». */
export const factsFallback = (brief: string): string =>
  ['• ' + brief.split(' | ').join('\n• '), '', 'Трактовка модели недоступна: выше — факты брифинга.'].join('\n');

/** Признак того, что раздел собран резервным способом. */
export const isRefusalFallback = (section: string): boolean =>
  section.endsWith('Трактовка модели недоступна: выше — факты брифинга.');

/**
 * Готовый ответ из состояния: отчёт отдаётся напрямую, анализ модели — своим
 * текстом. Опознание идёт по `kind`, а не по префиксу строки.
 */
export const answerOf = (state: { lastResult?: NodeResult | null }): string | undefined =>
  state.lastResult?.kind === 'report' ? state.lastResult.payload : undefined;
