import { DISCLAIMER } from '../report/portfolio-report.js';

/**
 * Инструкции для модели: что и в каком порядке показывать в ответе по портфелю.
 * Числа приходят из инструментов, модель их не пересчитывает.
 */
export const PORTFOLIO_REPORT_INSTRUCTIONS = [
  'Формат ответа по портфелю:',
  '1) список позиций: тикер, название, количество, текущая цена, стоимость позиции;',
  '2) итоговая стоимость портфеля;',
  '3) доходность — только если она есть в данных инструмента, иначе не упоминай её;',
  `4) источник данных и время данных (${'Tinkoff Invest'});`,
  '5) если портфель пуст — прямо скажи, что позиций нет;',
  '6) недоступные значения помечай словом «недоступно», не подставляй ноль или оценку;',
  `7) в конце добавь: «${DISCLAIMER}»`,
].join(' ');

export const buildPortfolioReportPrompt = (dataAsOf?: string): string =>
  dataAsOf
    ? `${PORTFOLIO_REPORT_INSTRUCTIONS} Время данных прогона: ${dataAsOf}.`
    : PORTFOLIO_REPORT_INSTRUCTIONS;
