import { DISCLAIMER } from '../report/portfolio-report.js';

/**
 * Инструкции для модели: что и в каком порядке показывать в ответе по портфелю.
 * Числа приходят из инструментов, модель их не пересчитывает.
 */
export const PORTFOLIO_REPORT_INSTRUCTIONS = [
  'Формат ответа по портфелю:',
  '1) по каждому счёту, где есть данные: название счёта, список позиций — тикер, количество, ' +
    'цена и стоимость позиции (если они есть в данных), итоговая стоимость и доходность счёта;',
  '2) общий итог по всем счетам;',
  '3) доходность показывай по каждому счёту, где брокер её вернул; не считай её сам;',
  `4) источник данных и время данных (${'Tinkoff Invest'});`,
  '5) если на счёте нет позиций — так и скажи по этому счёту; если состав или цена недоступны — напиши «недоступно»;',
  '6) недоступные значения помечай словом «недоступно», не подставляй ноль или оценку;',
  '7) не скрывай счета: перечисли все, по которым пришли данные, даже пустые;',
  '8) не отправляй пользователя «в приложение брокера», если данные есть в ответе инструмента;',
  `9) в конце добавь: «${DISCLAIMER}»`,
].join(' ');

export const buildPortfolioReportPrompt = (dataAsOf?: string): string =>
  dataAsOf
    ? `${PORTFOLIO_REPORT_INSTRUCTIONS} Время данных прогона: ${dataAsOf}.`
    : PORTFOLIO_REPORT_INSTRUCTIONS;
